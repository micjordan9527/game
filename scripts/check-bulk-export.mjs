import assert from "node:assert/strict"
import fs from "node:fs"
import matter from "gray-matter"
import ts from "typescript"

export async function checkBulkExport(page, base, prefix, width) {
  const source = ts.transpileModule(fs.readFileSync("src/data/articles.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
  const { articles } = await import("data:text/javascript;base64," + Buffer.from(source).toString("base64"))
  for (const slug of ["admin-bulk-actions", "export-masking-audit"]) {
    const { data } = matter(fs.readFileSync(`content/articles/${slug}.md`, "utf8"))
    const meta = articles.find((item) => item.slug === slug)
    for (const key of ["title", "description", "tags", "category", "audience", "difficulty"]) assert.deepEqual(data[key], meta[key], slug + ": " + key)
    assert.equal(data.updatedAt.toISOString().slice(0, 10), meta.updatedAt)
  }
  await page.goto(base + "/articles/admin-bulk-actions#bulk-action-demo", { waitUntil: "networkidle" })
  await page.locator("#article-details[open]").waitFor()
  const bulk = page.getByRole("region", { name: "后台批量操作演示", exact: true })
  await bulk.getByRole("button", { name: "选择当前页 3 条", exact: true }).click()
  assert((await bulk.locator("[data-bulk-selection]").innerText()).includes("已选 3 条"))
  await bulk.getByRole("button", { name: "批量关闭工单", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "确认批量关闭范围", exact: true })
  assert((await dialog.innerText()).includes("对象 3 条"))
  await page.keyboard.press("Escape"); await dialog.waitFor({ state: "hidden" })
  assert((await bulk.locator("details summary").innerText()).includes("0 批"), "Cancel does not submit a batch")
  await bulk.getByRole("button", { name: "选择全部匹配 8 条", exact: true }).click()
  await bulk.getByRole("button", { name: "批量关闭工单", exact: true }).click()
  assert((await dialog.innerText()).includes("全部匹配记录") && (await dialog.innerText()).includes("对象 8 条"))
  await dialog.getByRole("button", { name: "模拟一条状态变化", exact: true }).click()
  await dialog.getByRole("button", { name: "确认执行", exact: true }).evaluate((node) => { node.click(); node.click() })
  await dialog.getByRole("button", { name: "执行中…", exact: true }).waitFor()
  assert.equal(await dialog.getByRole("button", { name: "取消", exact: true }).isDisabled(), true)
  await dialog.locator("[data-bulk-result]").waitFor()
  assert.equal(await dialog.locator("[data-bulk-result]").innerText(), "成功 3 条 · 失败 1 条 · 跳过 4 条")
  await dialog.getByRole("button", { name: "仅选择失败项", exact: true }).click()
  await dialog.waitFor({ state: "hidden" })
  assert((await bulk.locator("[data-bulk-selection]").innerText()).includes("上次失败项 · 已选 1 条"))
  await bulk.getByRole("button", { name: "批量关闭工单", exact: true }).click()
  assert((await dialog.innerText()).includes("对象 1 条"))
  await dialog.getByRole("button", { name: "确认执行", exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[data-bulk-result]')?.textContent === "成功 1 条 · 失败 0 条 · 跳过 0 条")
  await dialog.getByRole("button", { name: "返回列表", exact: true }).click()
  await dialog.waitFor({ state: "hidden" })
  assert((await bulk.locator("details summary").innerText()).includes("2 批"), "Repeated click submits only one first batch")
  await bulk.locator("details summary").click()
  assert((await bulk.locator("details").innerText()).includes("BULK-DEMO-02 · 对象 1 条"))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.screenshot({ path: `/tmp/bulk-action-${width}.png` })
  await page.locator("#article-content .not-prose").first().scrollIntoViewIfNeeded()
  await page.locator("#article-content svg[id^=mermaid-]").waitFor()

  await page.goto(base + "/articles/export-masking-audit#export-task-demo", { waitUntil: "networkidle" })
  await page.locator("#article-details[open]").waitFor()
  const exp = page.getByRole("region", { name: "导出任务全过程演示", exact: true })
  const create = exp.getByRole("button", { name: "创建导出任务", exact: true })
  const generate = exp.getByRole("button", { name: "开始生成", exact: true })
  const downloadButton = exp.getByRole("button", { name: "请求下载示例CSV", exact: true })
  const waitState = (status) => exp.locator(`[data-export-state="${status}"]`).waitFor()
  let downloads = 0
  const capture = () => { downloads++ }
  page.on("download", capture)
  try {
    await create.evaluate((node) => { node.click(); node.click() })
    await waitState("排队中")
    await exp.getByRole("heading", { name: "EXP-DEMO-001", exact: true }).waitFor()
    await exp.getByLabel("下一任务的记录状态", { exact: true }).selectOption("已关闭")
    assert.equal(await exp.locator("[data-export-snapshot]").innerText(), "站点A · 全部 · 8条 · UTC+8")
    await generate.click(); await waitState("生成中"); await waitState("可下载")
    await exp.getByLabel("允许下载文件", { exact: true }).uncheck()
    await downloadButton.click(); await exp.getByRole("alert").filter({ hasText: "没有下载权限" }).waitFor()
    assert.equal(downloads, 0)
    await exp.getByLabel("允许下载文件", { exact: true }).check()
    await exp.getByLabel("当前站点", { exact: true }).selectOption("站点B")
    await downloadButton.click(); await exp.getByRole("alert").filter({ hasText: "站点与文件归属不一致" }).waitFor()
    assert.equal(downloads, 0)
    await exp.getByLabel("当前站点", { exact: true }).selectOption("站点A")
    const nextDownload = page.waitForEvent("download")
    await downloadButton.click(); const file = await nextDownload
    assert.equal(file.suggestedFilename(), "EXP-DEMO-001.csv")
    const csv = fs.readFileSync(await file.path(), "utf8")
    assert.equal(csv.replace(/^\ufeff/, "").split("\r\n").length, 9)
    assert(csv.includes('"DEMO-T008"') && csv.includes('"[已脱敏]"'))
    assert.equal(downloads, 1)
    await exp.getByRole("button", { name: "模拟链接过期", exact: true }).click()
    await downloadButton.click(); await exp.getByRole("alert").filter({ hasText: "任务已过期" }).waitFor()
    assert.equal(downloads, 1)
    await exp.getByLabel("模拟一次生成失败", { exact: true }).check()
    await create.click(); await generate.click(); await waitState("生成失败")
    await exp.getByRole("heading", { name: "EXP-DEMO-002", exact: true }).waitFor()
    assert((await exp.locator("[data-export-snapshot]").innerText()).includes("已关闭 · 3条"))
    await create.click(); await exp.getByLabel("允许创建导出", { exact: true }).uncheck()
    await generate.click(); await waitState("已取消")
    assert.equal(await create.isDisabled(), true)
    await exp.getByLabel("允许创建导出", { exact: true }).check()
    await create.click(); await exp.getByLabel("当前站点", { exact: true }).selectOption("站点B")
    await generate.click(); await waitState("已取消")
    await create.click(); await exp.getByRole("button", { name: "取消排队", exact: true }).click(); await waitState("已取消")
    await exp.locator("details").filter({ hasText: "查看本次演示事件记录" }).locator("summary").click()
    const history = await exp.innerText()
    assert(history.includes("EXP-DEMO-001 · 下载拒绝") && history.includes("EXP-DEMO-001 · 下载成功") && history.includes("EXP-DEMO-005 · 取消排队"))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
    await page.screenshot({ path: `/tmp/export-task-${width}.png` })
  } finally { page.off("download", capture) }
  for (const [slug, title] of [["admin-bulk-actions", "后台批量操作：范围确认与部分失败"], ["export-masking-audit", "数据导出、脱敏与下载审计"]]) {
    await page.goto(base + "/search?q=" + encodeURIComponent(title) + "&type=" + encodeURIComponent("文章"), { waitUntil: "networkidle" })
    await page.locator(`main a[href="${prefix}/articles/${slug}"]`).click()
    await page.locator("#article-details[open]").waitFor()
    await page.goBack({ waitUntil: "networkidle" })
    assert.equal(new URL(page.url()).searchParams.get("q"), title)
  }
  await page.goto(base + "/articles?role=interaction", { waitUntil: "networkidle" })
  for (const slug of ["admin-bulk-actions", "export-masking-audit"]) await page.locator(`[aria-label="文章列表"] a[href="${prefix}/articles/${slug}"]`).waitFor()
  await page.goto(base + "/updates#v24", { waitUntil: "networkidle" })
  const release = page.locator("#current-release")
  assert((await release.innerText()).includes("新增文章 1 篇 · 补充文章 1 篇"))
  assert(!(await release.innerText()).includes("GPT 配图"))
  await release.locator("#export-masking-audit-v24").waitFor()
  await page.goto(base + "/updates#export-masking-audit", { waitUntil: "networkidle" })
  assert.equal(await page.locator("#export-masking-audit").isVisible(), true)
  assert.equal(await page.locator("#export-masking-audit").evaluate((node) => !!node.closest("details[open]")), true)
  console.log(`PASS bulk/export ${width}px: page/all selection, cancellation, stale state, duplicate-click guard, partial results and failed-only retry, frozen export scope, CSV bytes, independent permissions/site/expiry, failure/cancel, search/role discovery and separate old/new release entries`)
}

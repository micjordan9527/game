import assert from "node:assert/strict"
import fs from "node:fs"
import matter from "gray-matter"
import ts from "typescript"

export async function checkPublicationMobile(page, base, prefix, width) {
  const source = ts.transpileModule(fs.readFileSync("src/data/articles.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
  const { articles } = await import("data:text/javascript;base64," + Buffer.from(source).toString("base64"))
  for (const [slug, count] of [["content-publication-versions", 5], ["mobile-page-layout", 6]]) {
    const { data, content } = matter(fs.readFileSync(`content/articles/${slug}.md`, "utf8"))
    const meta = articles.find((item) => item.slug === slug)
    for (const key of ["title", "description", "category", "tags", "audience", "difficulty"]) assert.deepEqual(data[key], meta[key], slug + ": " + key)
    assert.equal(data.updatedAt.toISOString().slice(0, 10), meta.updatedAt)
    const response = await page.goto(base + "/articles/" + slug + "#visual-guide", { waitUntil: "networkidle" })
    assert.equal(response.status(), 200)
    await page.locator("#article-details[open]").waitFor()
    const guide = page.locator("#visual-guide")
    assert.equal(await guide.locator("[data-guide-frame]").count(), count)
    assert.equal(await guide.locator("[data-guide-frame] button, [data-guide-frame] input").count(), 0)
    const boxes = await guide.locator("[data-guide-frame]").evaluateAll((nodes) => nodes.map((node) => {
      const r = node.getBoundingClientRect()
      const fonts = [...node.querySelectorAll("span, p, h3, h4, strong, small")].filter((item) => item.textContent.trim()).map((item) => parseFloat(getComputedStyle(item).fontSize))
      return { x: r.x, y: r.y, right: r.right, minFont: Math.min(...fonts) }
    }))
    for (const box of boxes) { assert(box.x >= 0 && box.right <= width + 1); assert(box.minFont >= 14) }
    if (width === 390) for (let i = 1; i < boxes.length; i++) assert(boxes[i].y > boxes[i - 1].y)
    for (const heading of content.matchAll(/^## (.+)$/gm)) {
      const id = heading[1].trim().toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, "").replace(/\s+/g, "-")
      assert.equal(await page.locator(`[id="${id}"]`).count(), 1)
    }
    await guide.getByRole("link", { name: "操作演示 ↓", exact: true }).click()
    assert.equal(new URL(page.url()).hash, slug === "mobile-page-layout" ? "#mobile-layout-demo" : "#publication-demo")
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
    await guide.locator("[data-guide-frame]").first().screenshot({ path: `/tmp/publication-mobile-scene-${slug}-${width}.png`, style: "body > header { visibility: hidden !important; }" })
  }
  await page.goto(base + "/articles/content-publication-versions#publication-demo", { waitUntil: "networkidle" })
  const demo = page.getByRole("region", { name: "公告审核与发布演示", exact: true })
  const click = async (name) => demo.getByRole("button", { name, exact: true }).click()
  const phase = async (value) => { await page.waitForFunction((value) => document.querySelector("[data-publication-phase]")?.textContent.endsWith(value), value) }
  const expectLive = async (value) => assert.equal(await demo.locator("[data-publication-live]").innerText(), "后台生效：" + value)
  const expectFront = async (value) => assert((await demo.locator("[data-publication-front]").innerText()).includes("前台可见：" + value))
  const approve = async () => { await click("提交审核"); await phase("待审核"); await click("审核通过（示例审核员）"); await phase("已审核") }
  const showHistory = async () => { const details = demo.locator("details"); if ((await details.getAttribute("open")) === null) await details.locator("summary").click() }
  const immediate = demo.getByRole("button", { name: "立即发布已审核版本", exact: true })
  assert.equal(await immediate.isDisabled(), true)
  await expectLive("v3"); await expectFront("v3")
  await click("记录当前可见版本")
  await click("提交审核"); await phase("待审核"); await click("审核驳回"); await phase("已驳回")
  assert.equal(await demo.getByLabel("内容标题", { exact: true }).isEnabled(), true)
  await demo.getByLabel("内容标题", { exact: true }).fill("帮助中心订单说明更新")
  await approve(); await click("安排10分钟后生效"); await phase("待生效")
  assert.equal(await demo.getByLabel("发布站点", { exact: true }).isDisabled(), true)
  await demo.getByLabel("模拟下一次发布失败", { exact: true }).check()
  await click("推进10分钟"); await phase("发布失败")
  await expectLive("v3"); await expectFront("v3")
  assert((await demo.getByRole("status").innerText()).includes("发布失败"))
  await immediate.evaluate((node) => { node.click(); node.click() }); await phase("已生效")
  await expectLive("v4"); await expectFront("v3")
  await showHistory()
  assert.equal(await demo.locator("[data-publication-history] li").filter({ hasText: "站点A / 中文 · v4 · 生效" }).count(), 1, "Repeated publish creates one version")
  await click("刷新前台快照"); await expectFront("v4"); await click("记录当前可见版本")
  await demo.getByLabel("前台语言", { exact: true }).selectOption("English")
  await expectLive("v3"); await expectFront("v3")
  await demo.getByLabel("前台站点", { exact: true }).selectOption("站点B")
  await expectLive("无"); await expectFront("无")
  await demo.getByLabel("前台站点", { exact: true }).selectOption("站点A"); await demo.getByLabel("前台语言", { exact: true }).selectOption("中文")
  await click("建立更正版本"); await phase("草稿")
  await demo.getByLabel("更正原因", { exact: true }).fill(""); await click("提交审核")
  assert((await demo.getByRole("status").innerText()).includes("更正原因"))
  await expectLive("v4")
  await demo.getByLabel("更正原因", { exact: true }).fill("修正帮助链接")
  await approve(); await click("立即发布已审核版本"); await phase("已生效")
  await expectLive("v5"); await expectFront("v4")
  await click("刷新前台快照"); await expectFront("v5")
  const history = await demo.locator("[data-publication-history]").innerText()
  assert(history.includes("v4 · 历史") && history.includes("v5 · 生效 · 更正v4：修正帮助链接"))
  const reads = await demo.locator("[data-publication-reads]").innerText()
  assert(reads.includes("中文 · v3") && reads.includes("中文 · v4"), "Old reading records retain original versions")
  await click("撤回当前版本"); await phase("已撤回"); await expectLive("无"); await expectFront("无")
  assert((await demo.locator("[data-publication-history]").innerText()).includes("v5 · 撤回"))

  await click("重置发布演示"); await approve(); await click("安排10分钟后生效")
  await click("修改稿件并重新审核"); await phase("草稿")
  assert((await demo.locator("[data-publication-task]").innerText()).includes("已失效"))
  await click("推进10分钟"); await expectLive("v3")
  assert.equal(await immediate.isDisabled(), true)
  await demo.getByLabel("发布站点", { exact: true }).selectOption("站点B")
  await demo.getByLabel("稿件语言", { exact: true }).selectOption("English")
  await click("提交审核")
  assert((await demo.getByRole("status").innerText()).includes("目标语言"))
  await demo.getByLabel("已核对本次目标语言内容（演示确认）", { exact: true }).check()
  await approve(); await click("安排10分钟后生效"); await click("推进10分钟"); await phase("已生效")
  await demo.getByLabel("前台站点", { exact: true }).selectOption("站点B"); await demo.getByLabel("前台语言", { exact: true }).selectOption("English")
  await expectLive("v5"); await expectFront("无"); await click("刷新前台快照"); await expectFront("v5")
  await demo.getByRole("button", { name: "推进10分钟", exact: true }).evaluate((node) => { node.click(); node.click(); node.click() })
  await phase("已到期"); await expectLive("无"); await expectFront("无")
  await showHistory(); assert((await demo.locator("[data-publication-history]").innerText()).includes("站点B / English · v5 · 到期"))
  await demo.getByLabel("前台站点", { exact: true }).selectOption("站点A")
  await expectLive("v3"); await expectFront("v3")
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await demo.screenshot({ path: `/tmp/publication-demo-${width}.png`, style: "body > header { visibility: hidden !important; }" })

  await page.goto(base + "/articles/mobile-page-layout#mobile-layout-demo", { waitUntil: "networkidle" })
  const mobile = page.getByRole("region", { name: "手机布局与信息优先级演示", exact: true })
  await mobile.getByRole("tab", { name: "手机", exact: true }).click()
  await mobile.getByText("手机端的设计判断", { exact: true }).waitFor()
  await mobile.getByRole("button", { name: "展开更多详情", exact: true }).click()
  await mobile.getByText("钱包流水 #WF-2418", { exact: true }).waitFor()
  await mobile.getByRole("button", { name: "收起详情", exact: true }).click()
  assert.equal(await mobile.getByText("钱包流水 #WF-2418", { exact: true }).count(), 0)
  for (const href of ["/cases/bm-optimization#bm-mobile-prototype", "/cases/competitor-analysis#u8-profile-prototype"]) await mobile.locator(`a[href="${prefix}${href}"]`).waitFor()
  const reference = page.getByRole("region", { name: "手机布局参考组", exact: true })
  for (const image of await reference.locator("img").all()) { await image.scrollIntoViewIfNeeded(); await image.evaluate((node) => node.decode()); assert(await image.evaluate((node) => node.naturalWidth > 1000)) }
  const trigger = reference.getByRole("button", { name: /查看完整长图/ }).first()
  await trigger.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
  const top = await page.evaluate(() => scrollY); await trigger.click()
  const dialog = page.getByRole("dialog"); await dialog.waitFor()
  await dialog.getByRole("region", { name: "图片浏览区域", exact: true }).locator("img").evaluate((node) => node.decode())
  await dialog.getByRole("button", { name: "原尺寸", exact: true }).click()
  await dialog.getByRole("button", { name: "适应屏幕", exact: true }).click()
  await dialog.getByRole("button", { name: "下一张", exact: true }).click()
  await dialog.getByRole("region", { name: "图片浏览区域", exact: true }).locator("img").evaluate((node) => node.decode())
  await page.keyboard.press("Escape"); await dialog.waitFor({ state: "hidden" })
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8, top)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.locator("#visual-guide [data-guide-frame]").nth(3).screenshot({ path: `/tmp/mobile-keyboard-scene-${width}.png`, style: "body > header { visibility: hidden !important; }" })
  for (const [slug, query] of [["mobile-page-layout", "手机页面布局"], ["content-publication-versions", "公告、帮助内容"]]) {
    await page.goto(base + "/search?q=" + encodeURIComponent(query) + "&type=" + encodeURIComponent("文章"), { waitUntil: "networkidle" })
    await page.locator(`main a[href="${prefix}/articles/${slug}"]`).click(); await page.locator("#visual-guide").waitFor()
    await page.goBack({ waitUntil: "networkidle" })
    assert.equal(new URL(page.url()).searchParams.get("q"), query); assert.equal(new URL(page.url()).searchParams.get("type"), "文章")
  }
  await page.goto(base + "/articles?role=interaction", { waitUntil: "networkidle" })
  for (const slug of ["mobile-page-layout", "content-publication-versions"]) await page.locator(`[aria-label="文章列表"] a[href="${prefix}/articles/${slug}"], [aria-label="文章列表"] a[href^="${prefix}/articles/${slug}?"]`).waitFor()
  await page.goto(base + "/design/mobile", { waitUntil: "networkidle" })
  await page.locator(`main a[href="${prefix}/articles/mobile-page-layout#visual-guide"]`).waitFor()
  await page.goto(base + "/updates#v26", { waitUntil: "networkidle" })
  const current = JSON.parse(fs.readFileSync("src/data/releaseHistory.json", "utf8")).current.version
  if (current !== 26) await page.locator("#v26[open]").waitFor()
  const release = page.locator(current === 26 ? "#current-release" : "#v26")
  assert((await release.innerText()).includes("新增文章 1 篇 · 补充文章 1 篇"))
  assert(!(await release.innerText()).includes("GPT 配图"))
  console.log(`PASS publication/mobile ${width}px: 11 readable scenes, review/rejection, frozen approval, manual scheduling/failure, duplicate publish guard, cache/language/site separation, correction/history/read versions, invalidated jobs, expiry/withdrawal, responsive details, BM/U8 image loading/viewer return, search/roles and release links`)
}

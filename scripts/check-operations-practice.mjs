export async function checkOperationsPractice(page, base, prefix, width) {
  const errors = []
  const onError = (error) => errors.push(error.message)
  page.on("pageerror", onError)
  try {
    await checkChannel(page, base, width)
    await checkCommunity(page, base, width)
    await checkCampaign(page, base, width)
    assert.deepEqual(errors, [], "Operations cases have no uncaught script errors")
    console.log(`PASS operations practice ${width}px ${prefix || "/"}: channel evidence/decision/archive, community reply/confirm/close, campaign v1/v2 snapshot and one 10 DEMO issue, keyboard/reset, open details/no overflow`)
  } finally {
    page.off("pageerror", onError)
  }
}

import assert from "node:assert/strict"

const isDisabled = async (button, expected = true) => assert.equal(await button.isDisabled(), expected, await button.innerText())
const contains = async (node, text) => assert((await node.innerText()).includes(text), `Expected visible text: ${text}`)

async function articleReady(page, base, slug, selector) {
  const response = await page.goto(`${base}/articles/${slug}`, { waitUntil: "networkidle" })
  assert.equal(response.status(), 200, slug)
  const guide = page.locator(selector)
  await guide.waitFor()
  assert.equal(await page.locator("#article-details").evaluate((node) => node.open), true, `${slug}: details default open`)
  assert(await guide.evaluate((node) => !!(node.compareDocumentPosition(document.querySelector("#article-details")) & Node.DOCUMENT_POSITION_FOLLOWING)), `${slug}: interface precedes prose`)
  return guide
}

async function noOverflow(page, guide, width) {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${width}px: no page overflow`)
  const frame = await guide.boundingBox()
  assert(frame && frame.x >= -1 && frame.x + frame.width <= width + 1, `${width}px: guide remains in viewport`)
}

async function capture(guide, name, width) {
  await guide.screenshot({ path: `/tmp/operations-${name}-${width}.png`, style: "body > header { visibility: hidden !important; }" })
}

async function checkChannel(page, base, width) {
  const guide = await articleReady(page, base, "channel-quality-review", "#channel-quality-case")
  const screen = guide.locator("[data-operation-screen]")
  const nav = guide.getByRole("navigation", { name: "切换案例界面", exact: true })
  const step = (label) => nav.getByRole("button", { name: new RegExp(label) })
  assert.equal(await nav.getByRole("button").count(), 4)
  await contains(screen, "CH-DEMO-021")
  await contains(screen, "未提供 · 需补充")
  await isDisabled(guide.getByRole("button", { name: "上一个界面", exact: true }))
  await capture(guide, "channel-profile", width)
  await screen.getByRole("button", { name: "记录缺少的材料", exact: true }).click()
  assert.equal(await step("异常记录").getAttribute("aria-current"), "step")
  await contains(screen, "CH-ISS-007")
  await contains(screen, "CH-DEMO-021")
  await screen.getByRole("button", { name: "打开这条异常的复核", exact: true }).click()
  const decision = screen.getByLabel("处理结论", { exact: true })
  assert.equal(await decision.inputValue(), "pause")
  assert.equal(await decision.locator('option[value="observe"]').evaluate((node) => node.disabled), true, "Cannot continue observation before supplement")
  await screen.getByRole("button", { name: "保存复核并归档", exact: true }).click()
  await contains(screen, "暂停合作")
  for (const id of ["CH-DEMO-021", "CH-ISS-007", "REV-DEMO-007"]) await contains(screen, id)
  await contains(screen, "保留 · 不删除")
  await isDisabled(guide.getByRole("button", { name: "下一个界面", exact: true }))
  await screen.getByRole("button", { name: "返回原异常记录", exact: true }).click()
  await contains(screen, "CH-ISS-007")
  await step("复核处理").click()
  await screen.getByRole("button", { name: "模拟收到并核对补充资料", exact: true }).click()
  assert.equal(await decision.locator('option[value="observe"]').evaluate((node) => node.disabled), false)
  await decision.selectOption("observe")
  await screen.getByRole("button", { name: "保存复核并归档", exact: true }).click()
  await contains(screen, "继续观察")
  await contains(screen, "ARC-DEMO-007")
  await contains(screen, "可按本次批准范围使用")
  await capture(guide, "channel-archive", width)
  await noOverflow(page, guide, width)
  for (const label of ["渠道资料", "异常记录", "复核处理", "归档结果"]) {
    await step(label).click()
    assert.equal(await step(label).getAttribute("aria-current"), "step")
    await noOverflow(page, guide, width)
  }
  await guide.getByRole("button", { name: "重看案例", exact: true }).click()
  assert.equal(await step("渠道资料").getAttribute("aria-current"), "step")
  await step("复核处理").click()
  assert.equal(await decision.inputValue(), "pause")
  assert.equal(await decision.locator('option[value="observe"]').evaluate((node) => node.disabled), true, "Restart clears supplemental evidence")
}


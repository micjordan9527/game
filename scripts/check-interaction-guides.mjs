import assert from "node:assert/strict"

export async function checkInteractionGuides(page, base, prefix, width) {
  const listPath = "/articles/admin-filter-list-states"
  const formPath = "/articles/form-validation-submit-feedback"
  await page.goto(base + listPath + "#list-demo", { waitUntil: "networkidle" })
  assert.equal(await page.locator("h1").count(), 1)
  await page.locator("#article-details[open]").waitFor()
  await page.locator("#article-content .not-prose").first().scrollIntoViewIfNeeded()
  await page.locator("#article-content svg[id^=mermaid-]").waitFor()
  const list = page.getByRole("region", { name: "后台筛选与列表演示", exact: true })
  const status = list.getByRole("status")
  assert((await status.innerText()).includes("共 8 条"))
  await list.getByLabel("记录状态", { exact: true }).selectOption("待处理")
  await list.getByLabel("排序", { exact: true }).selectOption("oldest")
  assert((await status.innerText()).includes("共 8 条"), "Draft filters do not relabel the old results")
  await list.getByRole("button", { name: "查询", exact: true }).click()
  await list.locator('[aria-busy="true"]').waitFor()
  await page.waitForFunction(() => document.querySelector('#list-demo [role="status"]').textContent.includes("共 5 条"))
  await list.getByRole("button", { name: "下一页", exact: true }).click()
  await list.getByText("第 2 / 2 页", { exact: true }).waitFor()
  const open = list.getByRole("button", { name: "查看 DEMO-T008 详情 →", exact: true })
  await open.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
  const top = await page.evaluate(() => scrollY)
  await open.click()
  await list.getByRole("region", { name: "记录详情", exact: true }).waitFor()
  await list.getByRole("button", { name: "← 返回原列表", exact: true }).click()
  await list.getByText("第 2 / 2 页", { exact: true }).waitFor()
  assert.equal(await list.getByLabel("记录状态", { exact: true }).inputValue(), "待处理")
  assert.equal(await list.getByLabel("排序", { exact: true }).inputValue(), "oldest")
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.activeElement?.getAttribute("data-record") === "DEMO-T008", top)
  await list.getByLabel("编号或标题", { exact: true }).fill("DEMO-T008")
  await list.getByRole("button", { name: "模拟查询失败", exact: true }).click()
  await list.getByRole("alert").waitFor()
  assert((await status.innerText()).includes("共 5 条"))
  await list.getByRole("button", { name: "重试当前条件", exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#list-demo [role="status"]').textContent.includes("共 1 条"))
  await list.getByText("第 1 / 1 页", { exact: true }).waitFor()
  await list.getByLabel("编号或标题", { exact: true }).fill("DEMO-NOT-FOUND")
  await list.getByRole("button", { name: "查询", exact: true }).click()
  await list.getByRole("heading", { name: "没有匹配记录", exact: true }).waitFor()
  await list.getByRole("button", { name: "清空条件", exact: true }).click()
  assert((await status.innerText()).includes("共 8 条"))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.screenshot({ path: `/tmp/interaction-list-${width}.png` })

  await page.goto(base + formPath + "#form-demo", { waitUntil: "networkidle" })
  await page.locator("#article-details[open]").waitFor()
  await page.locator("#article-content .not-prose").first().scrollIntoViewIfNeeded()
  await page.locator("#article-content svg[id^=mermaid-]").waitFor()
  const form = page.getByRole("region", { name: "表单校验与提交演示", exact: true })
  const submit = form.getByRole("button", { name: "提交演示申请", exact: true })
  const title = form.getByLabel("公告标题", { exact: true })
  const summary = form.getByLabel("内容摘要", { exact: true })
  const fill = async () => { await title.fill("帮助中心内容更新"); await summary.fill("调整帮助中心的订单说明与常见问题分类。"); }
  await submit.click()
  await form.getByRole("alert").waitFor()
  assert.equal(await title.getAttribute("aria-invalid"), "true")
  assert.equal(await summary.getAttribute("aria-invalid"), "true")
  assert.equal(await title.evaluate((node) => node === document.activeElement), true)
  assert.equal(await form.locator("[data-submit-attempts]").count(), 0)
  await fill()
  await submit.click()
  await form.locator('[data-form-phase="submitting"]').waitFor()
  assert.equal(await form.getByRole("button", { name: "提交中…", exact: true }).isDisabled(), true)
  assert.equal(await form.getByRole("button", { name: "重置演示", exact: true }).isDisabled(), true)
  await form.locator('[data-form-phase="unknown"]').waitFor()
  assert.equal(await submit.isDisabled(), true)
  assert.equal(await title.inputValue(), "帮助中心内容更新")
  assert.equal(await form.locator("[data-submit-attempts]").innerText(), "1")
  await form.getByRole("button", { name: "查询原申请结果", exact: true }).click()
  await form.locator('[data-form-phase="querying"]').waitFor()
  await form.locator('[data-form-phase="accepted"]').waitFor()
  assert.equal(await form.locator("[data-submit-attempts]").innerText(), "1")
  assert((await form.getByRole("status").innerText()).includes("公告尚未发布"))
  await form.getByRole("button", { name: "重置演示", exact: true }).click()
  await form.getByLabel("演示响应", { exact: true }).selectOption("rejected")
  await fill(); await submit.click()
  await form.locator('[data-form-phase="rejected"]').waitFor()
  assert.equal(await title.isEnabled(), true)
  assert.equal(await title.inputValue(), "帮助中心内容更新")
  await form.getByLabel("演示响应", { exact: true }).selectOption("accepted")
  await submit.click()
  await form.locator('[data-form-phase="accepted"]').waitFor()
  assert.equal(await form.locator("[data-submit-attempts]").innerText(), "2")
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await page.screenshot({ path: `/tmp/interaction-form-${width}.png` })

  for (const [path, titleText] of [[listPath, "后台筛选与列表状态：从查询到详情返回"], [formPath, "表单校验与提交反馈：从字段错误到未知结果"]]) {
    await page.goto(base + "/search?q=" + encodeURIComponent(titleText) + "&type=" + encodeURIComponent("文章"), { waitUntil: "networkidle" })
    const link = page.locator(`main a[href="${prefix}${path}"]`)
    await link.waitFor(); await link.click()
    await page.locator("#article-details[open]").waitFor()
    await page.goBack({ waitUntil: "networkidle" })
    assert.equal(new URL(page.url()).searchParams.get("q"), titleText)
    assert.equal(new URL(page.url()).searchParams.get("type"), "文章")
  }
  for (const role of ["interaction", "design"]) {
    await page.goto(base + "/articles?role=" + role, { waitUntil: "networkidle" })
    for (const path of [listPath, formPath]) await page.locator(`[aria-label="文章列表"] a[href="${prefix}${path}"]`).waitFor()
  }
  await page.goto(base + "/updates#v22", { waitUntil: "networkidle" })
  await page.locator("#v22[open]").waitFor()
  const release = page.locator("#v22")
  assert((await release.innerText()).includes("新增文章 2 篇"))
  assert(!(await release.innerText()).includes("GPT 配图"), "No generated image is attributed to interactive demos")
  console.log(`PASS interaction guides ${width}px: applied/draft filters, loading/failure/retry/empty, pagination and detail return/focus, field errors, submitting/unknown/original lookup/rejected/accepted, search return, both roles and accurate release counts`)
}

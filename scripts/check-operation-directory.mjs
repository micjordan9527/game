import assert from "node:assert/strict"
import fs from "node:fs"
import ts from "typescript"

export async function checkOperationDirectory(page, base, prefix, width) {
  const source = ["src/data/articles.ts", "src/data/operationGroups.ts"].map((file) => fs.readFileSync(file, "utf8")).join("\n")
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
  const { articles, operationGroups, operationReferenceSlugs } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"))
  const orderedSlugs = operationGroups.flatMap((group) => group.entries.map((entry) => entry.slug))
  assert.equal(new Set(orderedSlugs).size, orderedSlugs.length, "One primary operation category per article")
  assert([...orderedSlugs, ...operationReferenceSlugs].every((slug) => articles.some((article) => article.slug === slug)))
  assert(articles.filter((article) => article.category === "operation").every((article) => [...orderedSlugs, ...operationReferenceSlugs].includes(article.slug)), "Retain every existing operation article")
  const directory = () => page.getByRole("region", { name: "运营工作目录", exact: true })
  const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, page.url())
  const paths = async (locator) => (await locator.evaluateAll((links) => links.map((link) => link.getAttribute("href")))).map((href) => new URL(href, base).pathname)
  const choose = async (slug) => {
    await directory().locator(`button[data-operation-filter="${slug}"]`).click()
    await directory().locator(`button[data-operation-filter="${slug}"][aria-pressed="true"]`).waitFor()
  }
  await page.goto(base + "/operation", { waitUntil: "networkidle" })
  await directory().waitFor()
  assert.deepEqual(await directory().locator("[data-operation-group]").evaluateAll((groups) => groups.map((group) => group.dataset.operationGroup)), operationGroups.map((group) => group.slug))
  assert.equal(await directory().getByRole("button").count(), 6)
  assert.equal(await directory().locator("article").count(), orderedSlugs.length + operationReferenceSlugs.length)
  for (const group of operationGroups) {
    const section = directory().locator(`[data-operation-group="${group.slug}"]`)
    const expected = group.entries.map((entry) => prefix + "/articles/" + entry.slug)
    assert.deepEqual(await paths(section.locator("article a")), expected)
    assert.deepEqual(await paths(section.locator("ol a")), expected, "The sequence and cards share one order")
  }
  await page.screenshot({ path: `/tmp/operation-directory-${width}.png` })
  await choose("website")
  assert.equal(new URL(page.url()).searchParams.get("group"), "website")
  await page.reload({ waitUntil: "networkidle" })
  assert.equal(await directory().locator("[data-operation-group]").count(), 1)
  assert.equal(await directory().locator("article").count(), 2)
  const first = directory().locator("article h3").first()
  await first.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const websiteTop = await page.evaluate(() => scrollY)
  await first.click()
  await page.waitForURL((url) => url.pathname === prefix + "/articles/content-publication-versions" && url.searchParams.get("operation") === "website")
  const breadcrumb = () => page.getByRole("navigation", { name: "文章位置", exact: true })
  await breadcrumb().getByRole("link", { name: "网站运营", exact: true }).waitFor()
  if (width < 1280) await page.locator("body > header").getByRole("button", { name: "打开导航", exact: true }).click()
  const menu = width < 1280 ? page.getByRole("dialog", { name: "知识库导航", exact: true }) : page.locator("aside")
  assert.equal(await menu.locator(`a[href="${prefix}/operation"][aria-current="location"]`).count(), 1, "The operation parent remains active for a cross-topic article")
  assert.equal(await menu.locator(`a[href^="${prefix}/articles/content-publication-versions?"][aria-current="page"]`).count(), 1)
  if (width < 1280) await page.keyboard.press("Escape")
  assert.equal(new URL(await page.locator('link[rel="canonical"]').getAttribute("href")).pathname, prefix + "/articles/content-publication-versions", "The canonical article URL is preserved")
  let pager = page.getByRole("navigation", { name: "连续阅读", exact: true })
  assert((await pager.innerText()).includes("第 1 / 2 篇"))
  await pager.getByRole("link").filter({ hasText: "下一篇" }).click()
  await page.waitForURL((url) => url.pathname === prefix + "/articles/game-catalog-availability" && url.searchParams.get("operation") === "website")
  await breadcrumb().getByRole("link", { name: "网站运营", exact: true }).waitFor()
  pager = page.getByRole("navigation", { name: "连续阅读", exact: true })
  assert((await pager.innerText()).includes("第 2 / 2 篇"))
  await pager.getByRole("link", { name: "返回运营目录", exact: true }).first().click()
  await directory().locator('[data-operation-filter="website"][aria-pressed="true"]').waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8, websiteTop)
  await noOverflow()
  await page.screenshot({ path: `/tmp/operation-website-${width}.png` })

  await choose("traffic")
  const traffic = directory().locator('[data-operation-group="traffic"]')
  assert.equal(await traffic.locator("article").count(), 3)
  await traffic.locator(`article a[href^="${prefix}/articles/tg-message-media?"]`).click()
  await breadcrumb().getByRole("link", { name: "流量运营", exact: true }).waitFor()
  pager = page.getByRole("navigation", { name: "连续阅读", exact: true })
  assert((await pager.innerText()).includes("第 2 / 3 篇"))
  assert.equal(new URL(await pager.getByRole("link").filter({ hasText: "下一篇" }).getAttribute("href"), base).pathname, prefix + "/articles/operation-product-conversion-model")
  assert.equal(await page.getByRole("heading", { name: "TG推送截图", exact: true }).count(), 0)
  await page.goBack({ waitUntil: "networkidle" })
  await directory().locator('[data-operation-filter="traffic"][aria-pressed="true"]').waitFor()

  await choose("all")
  const references = directory().locator("details[data-operation-references]")
  await references.locator("summary").click()
  const referenceHeading = references.locator("article h3").first()
  await referenceHeading.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const referenceTop = await page.evaluate(() => scrollY)
  await referenceHeading.click()
  await page.waitForURL((url) => url.pathname === prefix + "/articles/payment-channel-basic")
  pager = page.getByRole("navigation", { name: "连续阅读", exact: true })
  assert((await pager.innerText()).includes("相关参考"))
  if (width < 1280) await page.locator("body > header").getByRole("button", { name: "打开导航", exact: true }).click()
  const referenceMenu = width < 1280 ? page.getByRole("dialog", { name: "知识库导航", exact: true }) : page.locator("aside")
  assert.equal(await referenceMenu.locator(`a[href^="${prefix}/articles/payment-channel-basic?"][aria-current="page"]`).count(), 1)
  if (width < 1280) await page.keyboard.press("Escape")
  await pager.getByRole("link", { name: "返回运营目录 →", exact: true }).click()
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.querySelector("details[data-operation-references]")?.open, referenceTop)

  await page.goto(base + "/articles?role=operation", { waitUntil: "networkidle" })
  await directory().waitFor()
  assert.deepEqual(await directory().locator("[data-operation-group]").evaluateAll((groups) => groups.map((group) => group.dataset.operationGroup)), operationGroups.map((group) => group.slug))
  const rolePaths = await paths(directory().locator("article a"))
  assert.equal(new Set(rolePaths).size, rolePaths.length, "Each role article appears once across groups and references")
  await choose("website")
  assert.equal(new URL(page.url()).searchParams.get("role"), "operation")
  assert.equal(await directory().locator("article").count(), 2)
  const tags = page.locator("details[data-article-tags]")
  if (!await tags.evaluate((node) => node.open)) await tags.locator("summary").click()
  await page.getByRole("group", { name: "标签筛选", exact: true }).locator('button[data-filter-value="TG推送"]').click()
  await page.waitForURL((url) => url.searchParams.get("tag") === "TG推送" && !url.searchParams.has("group"))
  assert.deepEqual(await directory().locator("[data-operation-group]").evaluateAll((groups) => groups.map((group) => group.dataset.operationGroup)), ["traffic"], "Empty categories disappear for filtered results")
  const tg = directory().locator("article h3")
  await tg.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const libraryTop = await page.evaluate(() => scrollY)
  await tg.click()
  await breadcrumb().getByRole("link", { name: "流量运营", exact: true }).waitFor()
  await page.getByRole("navigation", { name: "连续阅读", exact: true }).getByRole("link", { name: "返回运营目录", exact: true }).first().click()
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.querySelector("details[data-article-tags]")?.open, libraryTop)
  assert.equal(new URL(page.url()).searchParams.get("role"), "operation")
  assert.equal(new URL(page.url()).searchParams.get("tag"), "TG推送")
  await noOverflow()

  await page.goto(base + "/articles/content-publication-versions", { waitUntil: "networkidle" })
  await breadcrumb().getByRole("link", { name: "产品设计", exact: true }).waitFor()
  assert.equal(await breadcrumb().getByRole("link", { name: "网站运营", exact: true }).count(), 0, "Direct article browsing keeps its original topic")
  await page.goto(base + "/search?q=" + encodeURIComponent("网站运营"), { waitUntil: "networkidle" })
  await page.locator(`main a[href="${prefix}/operation?group=website"]`).waitFor()
  console.log(`PASS operations ${width}px: five categories, ordered unique articles, cross-topic reading, explicit/browser return, role/tag filters and position, canonical URLs and search`)
}

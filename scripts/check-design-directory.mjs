import assert from "node:assert/strict"
import fs from "node:fs"
import ts from "typescript"

export async function checkDesignDirectory(page, base, prefix, width) {
  const source = ["src/data/articles.ts", "src/data/designObjects.ts"].map((file) => fs.readFileSync(file, "utf8")).join("\n")
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
  const { articles, designObjects, designArticleEntries, designResources } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"))
  assert.equal(new Set(designArticleEntries.map((item) => item.slug)).size, designArticleEntries.length)
  for (const entry of [...designArticleEntries, ...designResources]) {
    const object = designObjects.find((item) => item.slug === entry.object)
    assert(object?.directions.some((item) => item.slug === entry.direction), "Each resource has one valid primary design object and direction")
    if (entry.slug) assert(articles.some((item) => item.slug === entry.slug))
  }
  assert(articles.filter((item) => item.category === "design").every((article) => designArticleEntries.some((entry) => entry.slug === article.slug)))
  const directory = () => page.getByRole("region", { name: "设计对象目录", exact: true })
  const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, page.url())
  const paths = async (locator) => (await locator.evaluateAll((links) => links.map((link) => link.getAttribute("href")))).map((href) => new URL(href, base).pathname)
  const chooseObject = async (slug) => {
    await directory().locator(`button[data-design-object="${slug}"]`).click()
    await page.locator(`[data-design-directory][data-selected-object="${slug}"]`).waitFor()
  }
  const chooseDirection = async (slug) => {
    await directory().locator(`button[data-design-direction="${slug}"]`).click()
    await page.locator(`[data-design-directory][data-selected-direction="${slug}"]`).waitFor()
  }
  const headingTop = async (heading) => {
    await heading.evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
    await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    return page.evaluate(() => scrollY)
  }
  const breadcrumb = () => page.getByRole("navigation", { name: "文章位置", exact: true })
  const pager = () => page.getByRole("navigation", { name: "连续阅读", exact: true })
  const returnLink = () => pager().getByRole("link", { name: /返回设计目录/ }).first()

  await page.goto(base + "/design", { waitUntil: "networkidle" })
  await directory().waitFor()
  await page.screenshot({ path: `/tmp/design-objects-first-${width}.png` })
  assert.deepEqual(await directory().locator("[data-design-section]").evaluateAll((nodes) => nodes.map((node) => node.dataset.designSection)), designObjects.map((item) => item.slug), "Design taxonomy does not depend on existing article coverage")
  assert.equal(await directory().locator("article").count(), designArticleEntries.length)
  assert.equal(await directory().locator("[data-design-resource]").count(), designResources.length)
  assert.deepEqual((await paths(directory().locator("article a"))).sort(), designArticleEntries.map((entry) => prefix + "/articles/" + entry.slug).sort())
  for (const image of await directory().locator("[data-design-resource] img").all()) {
    await image.scrollIntoViewIfNeeded(); await image.evaluate((node) => node.decode())
    assert(await image.evaluate((node) => node.naturalWidth > 0), "Existing resource previews load")
  }
  const brand = directory().locator('[data-design-section="brand"]')
  assert.equal(await brand.locator(`a[href="${prefix}/design/material-standards?module=brand-logo"]`).count(), 1)
  assert.equal(await brand.locator("[data-design-resource=brand-system]").count(), 1)
  assert((await brand.locator("[data-design-resource=brand-system] img").getAttribute("src")).endsWith("/output-01-brand-overview.webp"), "Show the design result rather than its prompt screenshot")
  assert((await directory().locator("[data-design-resource=ui-system] img").getAttribute("src")).endsWith("/output-01-overview.webp"))
  assert((await brand.locator("[data-design-resource=brand-logo]").boundingBox()).height < 350, "Short resource cards do not stretch to the neighboring image card")
  const physical = directory().locator('[data-design-section="physical"]')
  assert.equal(await physical.locator("article, [data-design-resource]").count(), 0)
  assert((await physical.innerText()).includes("暂无独立设计案例"))
  assert.equal(await directory().locator('[data-design-references="communication"] article').count(), 1, "Equipment anatomy is an illustration reference, not a physical design case")
  await chooseObject("digital")
  assert.equal(await directory().locator("[data-design-direction]").count(), 7)
  await chooseDirection("research")
  assert.equal(await directory().locator("article, [data-design-resource]").count(), 0)
  await directory().locator("[data-design-empty]").waitFor()
  await chooseDirection("interaction")
  assert.equal(await directory().locator("article").count(), 5)
  const types = directory().locator("details[data-design-types]")
  if (!await types.evaluate((node) => node.open)) await types.locator("summary").click()
  await directory().locator('[data-design-format="article"]').click()
  await page.locator('[data-design-directory][data-selected-format="article"]').waitFor()
  assert.equal(await directory().locator("[data-design-resource]").count(), 0)
  await page.reload({ waitUntil: "networkidle" })
  await page.locator('[data-design-directory][data-selected-object="digital"][data-selected-direction="interaction"][data-selected-format="article"]').waitFor()
  const reloadedTypes = directory().locator("details[data-design-types]")
  if (!await reloadedTypes.evaluate((node) => node.open)) await reloadedTypes.locator("summary").click()
  await noOverflow()
  await page.screenshot({ path: `/tmp/design-directory-${width}.png` })

  const first = directory().locator('article a[href*="/admin-filter-list-states?"] h3')
  const interactionTop = await headingTop(first)
  await first.click()
  await page.waitForURL((url) => url.pathname === prefix + "/articles/admin-filter-list-states" && url.searchParams.get("design") === "digital")
  await breadcrumb().getByRole("link", { name: "数字产品设计", exact: true }).waitFor()
  await breadcrumb().getByRole("link", { name: "交互设计", exact: true }).waitFor()
  await page.locator("#article-details[open]").waitFor()
  assert.equal(new URL(await page.locator('link[rel="canonical"]').getAttribute("href")).pathname, prefix + "/articles/admin-filter-list-states")
  if (width < 1280) await page.locator("body > header").getByRole("button", { name: "打开导航", exact: true }).click()
  const menu = width < 1280 ? page.getByRole("dialog", { name: "知识库导航", exact: true }) : page.locator("body > div aside").first()
  assert.equal(await menu.locator(`a[href="${prefix}/design"][aria-current="location"]`).count(), 1)
  assert.equal(await menu.locator(`a[href^="${prefix}/articles/admin-filter-list-states?"][aria-current="page"]`).count(), 1)
  if (width < 1280) await page.keyboard.press("Escape")
  assert((await pager().innerText()).includes("第 1 / 3 篇"))
  await pager().getByRole("link").filter({ hasText: "下一篇" }).click()
  await page.waitForURL((url) => url.pathname === prefix + "/articles/admin-bulk-actions")
  await breadcrumb().getByRole("link", { name: "交互设计", exact: true }).waitFor()
  assert((await pager().innerText()).includes("第 2 / 3 篇"))
  const origin = new URL(new URL(page.url()).searchParams.get("returnTo"), "https://knowledge.invalid")
  assert.equal(origin.searchParams.get("format"), "article")
  await returnLink().click()
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.querySelector("details[data-design-types]")?.open, interactionTop)
  assert.equal(new URL(page.url()).searchParams.get("direction"), "interaction")

  const references = directory().locator('[data-design-references="digital"]')
  await references.locator("summary").click()
  const reference = references.locator("article h3").first(), referenceTop = await headingTop(reference)
  await reference.click()
  await pager().waitFor()
  assert((await pager().innerText()).includes("相关参考"))
  assert.equal(await pager().getByRole("link").filter({ hasText: "下一篇" }).count(), 0)
  await page.goBack({ waitUntil: "networkidle" })
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.querySelector('[data-design-references="digital"]')?.open, referenceTop)

  await page.goto(base + "/articles?role=design&object=digital&direction=interaction&format=article", { waitUntil: "networkidle" })
  await directory().waitFor()
  const tags = page.locator("details[data-article-tags]")
  if (!await tags.evaluate((node) => node.open)) await tags.locator("summary").click()
  await page.getByRole("group", { name: "标签筛选", exact: true }).locator('button[data-filter-value="批量操作"]').click()
  await page.waitForURL((url) => url.searchParams.get("tag") === "批量操作" && !url.searchParams.has("object") && !url.searchParams.has("direction") && !url.searchParams.has("format"))
  assert.deepEqual(await directory().locator("[data-design-section]").evaluateAll((nodes) => nodes.map((node) => node.dataset.designSection)), ["digital"])
  assert.equal(await directory().locator("[data-design-resource]").count(), 0, "A tag filter never adds unrelated resources")
  const roleHeading = directory().locator("article h3"), libraryTop = await headingTop(roleHeading)
  await roleHeading.click()
  await returnLink().click()
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8 && document.querySelector("details[data-article-tags]")?.open, libraryTop)
  assert.equal(new URL(page.url()).searchParams.get("role"), "design")
  assert.equal(new URL(page.url()).searchParams.get("tag"), "批量操作")

  await page.goto(base + "/design?object=digital&direction=system", { waitUntil: "networkidle" })
  const component = directory().locator('[data-design-resource="components"] a'), componentTop = await headingTop(component)
  await component.click()
  await page.getByRole("tab", { name: "业务组件", exact: true, selected: true }).waitFor()
  assert.equal(new URL(page.url()).hash, "#component")
  await noOverflow()
  await page.getByRole("link", { name: "← 返回设计目录", exact: true }).click()
  await directory().waitFor()
  await page.waitForFunction((top) => Math.abs(scrollY - top) < 8, componentTop)
  assert.equal(new URL(page.url()).searchParams.get("direction"), "system")

  await page.goto(base + "/design/material-standards?module=brand-logo", { waitUntil: "networkidle" })
  assert.equal(await page.locator("[data-context-navigation]").count(), 0, "Agent materials keeps its own independent workspace")
  await page.goto(base + "/articles/content-publication-versions?operation=website&returnTo=%2Foperation%3Fgroup%3Dwebsite", { waitUntil: "networkidle" })
  await breadcrumb().getByRole("link", { name: "网站运营", exact: true }).waitFor()
  assert.equal(await breadcrumb().getByRole("link", { name: "数字产品设计", exact: true }).count(), 0)
  await page.goto(base + "/articles/content-publication-versions", { waitUntil: "networkidle" })
  await breadcrumb().getByRole("link", { name: "产品设计", exact: true }).waitFor()
  await page.goto(base + "/search?q=" + encodeURIComponent("信息架构"), { waitUntil: "networkidle" })
  await page.locator(`main a[href="${prefix}/design?object=digital&direction=architecture"]`).waitFor()
  await noOverflow()
  console.log(`PASS design directory ${width}px: four independent objects, six digital directions, exact unique articles and typed existing resources, honest gaps and device-reference distinction, URL filters, contextual reading, role/tag/type/disclosure/scroll return, demo hash, independent materials, original topics and search`)
}

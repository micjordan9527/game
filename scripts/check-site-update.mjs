import assert from "node:assert/strict"

const routes = ["/", "/cases", "/cases/admin-optimization", "/cases/bm-optimization", "/cases/competitor-analysis", "/cases/white-label-official", "/search", "/articles/member-account-states", "/ai-workflows/brand-visual-system", "/ai-workflows/ui-design-system"]
const pauseForLayout = (page) => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))

export async function checkSiteUpdate(page, base, prefix, width) {
  for (const route of routes) {
    const response = await page.goto(base + route, { waitUntil: "networkidle" })
    assert.equal(response.status(), 200, route)
    assert.equal(await page.locator("main h1").count(), 1, route)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${route}: page overflow`)
    const body = await page.locator("main").innerText()
    assert(!/作品案例|作业|打卡|答题|后续新增|规划中|已接入/.test(body), `${route}: copy`)
    const images = await page.locator("main img").evaluateAll((nodes) => nodes.filter((image) => image.complete && !image.naturalWidth).map((image) => image.src))
    assert.deepEqual(images, [], `${route}: broken loaded images`)
  }

  for (const [slug, nativeWidth] of [["bm-optimization", 1600], ["competitor-analysis", 2160]]) {
    await page.goto(`${base}/cases/${slug}`, { waitUntil: "networkidle" })
    const trigger = page.getByRole("region", { name: "案例长图组" }).locator("article button").first()
    await trigger.scrollIntoViewIfNeeded()
    const before = await page.evaluate(() => window.scrollY)
    await trigger.click()
    const dialog = page.getByRole("dialog")
    await dialog.waitFor()
    const image = dialog.getByRole("region", { name: "图片浏览区域" }).locator("img")
    await image.evaluate((node) => node.decode())
    const viewport = dialog.getByRole("region", { name: "图片浏览区域" })
    const fit = await image.boundingBox(), view = await viewport.boundingBox()
    assert(fit.width <= view.width && fit.height <= view.height, `${slug}: fit screen`)
    await dialog.getByRole("button", { name: "原尺寸", exact: true }).click()
    assert.equal(Math.round((await image.boundingBox()).width), nativeWidth, `${slug}: native width`)
    await viewport.evaluate((node) => { node.scrollLeft = 420; node.scrollTop = 500 })
    const scrolled = await viewport.evaluate((node) => ({ x: node.scrollLeft, y: node.scrollTop }))
    assert(scrolled.x > 0 && scrolled.y > 0, `${slug}: both axes scroll at native size`)
    await dialog.getByRole("button", { name: "下一张", exact: true }).click()
    assert.match(await dialog.getByRole("heading").innerText(), /详情页|个人中心/)
    assert.equal(await dialog.getByRole("button", { name: "原尺寸", exact: true }).getAttribute("aria-pressed"), "true")
    assert.equal(await viewport.evaluate((node) => node.scrollTop), 0, "New image starts at top")
    await dialog.getByRole("button", { name: "上一张", exact: true }).click()
    const thumbnails = dialog.getByRole("button", { name: /^查看/ })
    await thumbnails.nth(1).click()
    assert.equal(await thumbnails.nth(1).getAttribute("aria-pressed"), "true")
    await dialog.getByRole("button", { name: "适应屏幕", exact: true }).click()
    await thumbnails.first().click()
    await page.screenshot({ path: `/tmp/knowledge-${slug}-${width}.png` })
    // Keyboard navigation and trapped focus remain available in both display modes.
    await page.keyboard.press("ArrowRight")
    assert.match(await dialog.getByRole("heading").innerText(), /详情页|个人中心/)
    await dialog.getByRole("button", { name: "关闭", exact: true }).focus()
    await page.keyboard.press("Shift+Tab")
    assert.equal(await dialog.evaluate((node) => node.contains(document.activeElement)), true)
    await page.keyboard.press("Escape")
    await dialog.waitFor({ state: "hidden" })
    await pauseForLayout(page)
    assert(Math.abs((await page.evaluate(() => window.scrollY)) - before) <= 2, `${slug}: reading position restored`)
    assert.equal(await trigger.evaluate((node) => document.activeElement === node), true)
  }
  console.log(`PASS image viewing ${width}px: BM/U8 fit, native dimensions, both scroll axes, next/previous, thumbnails, keyboard, focus and reading position`)

  await page.goto(`${base}/cases/white-label-official`, { waitUntil: "networkidle" })
  const nav = page.getByRole("navigation", { name: "官网模块定位" })
  for (const [title, target] of [["服务展示", "solution"], ["页面结构", "product"], ["咨询入口", "contact"]]) {
    await nav.getByRole("link", { name: title, exact: true }).click()
    assert.equal(await nav.getByRole("link", { name: title, exact: true }).getAttribute("aria-current"), "location")
    const frame = page.frameLocator('iframe[title="包网官网案例预览"]')
    await frame.locator(`#${target}`).waitFor({ state: "visible" })
    await page.waitForFunction(({ target }) => {
      // The frame is sandboxed: use Playwright's frame context below for DOM checks.
      return document.querySelector('iframe[title="包网官网案例预览"]').getAttribute('src').endsWith('#' + target)
    }, { target })
    await frame.locator(`#${target}`).evaluate((node) => new Promise((resolve) => {
      const started = Date.now()
      const check = () => {
        const box = node.getBoundingClientRect()
        if (location.hash === `#${node.id}` && box.top >= -2 && box.top < 160) resolve(true)
        else if (Date.now() - started > 5000) resolve(false)
        else requestAnimationFrame(check)
      }
      check()
    })).then((visible) => assert(visible, `${title}: section not positioned in actual frame`))
    assert.equal(await frame.locator("body").evaluate((body) => body.scrollWidth > innerWidth + 1), false, `${title}: embedded page overflow`)
  }
  await page.reload({ waitUntil: "networkidle" })
  assert.equal(await nav.getByRole("link", { name: "咨询入口", exact: true }).getAttribute("aria-current"), "location", "Module hash survives reload")
  await page.screenshot({ path: `/tmp/knowledge-official-${width}.png` })
  console.log(`PASS official modules ${width}px: service/structure/contact positioning, diagrams, captions and reload`)

  await page.goto(`${base}/search`, { waitUntil: "networkidle" })
  const recommendations = page.getByRole("region", { name: "精选资料", exact: true })
  assert.equal(await recommendations.getByRole("link").count(), 6)
  for (const group of ["精选案例", "精选功能图解", "精选AI 工作流"]) assert.equal(await page.getByRole("region", { name: group, exact: true }).getByRole("link").count(), 2)
  await page.screenshot({ path: `/tmp/knowledge-search-${width}.png` })
  const input = page.getByRole("textbox", { name: "搜索知识库", exact: true })
  await input.pressSequentially("api", { delay: 25 })
  assert.equal(await input.inputValue(), "api", "Sequential typing must retain each character")
  await input.fill("钱包")
  await page.getByRole("button", { name: /^文章 \(/ }).waitFor()
  assert.equal(await page.locator('[aria-label="搜索结果类型"]').getByRole("button", { name: /\(0\)/ }).count(), 0)
  await page.getByRole("button", { name: /^文章 \(/ }).click()
  assert.equal(new URL(page.url()).searchParams.get("type"), "文章")
  const result = page.locator(`main a[href^="${prefix}/articles/"]`).last()
  await result.scrollIntoViewIfNeeded()
  await pauseForLayout(page)
  const before = await page.evaluate(() => window.scrollY)
  await result.click()
  await page.waitForURL(/\/articles\//)
  await page.goBack({ waitUntil: "networkidle" })
  await pauseForLayout(page)
  assert.equal(await input.inputValue(), "钱包")
  assert.equal(await page.getByRole("button", { name: /^文章 \(/ }).getAttribute("aria-pressed"), "true")
  const after = await page.evaluate(() => window.scrollY)
  assert(Math.abs(after - before) <= 3, `Search reading position: ${before} -> ${after}`)
  await page.reload({ waitUntil: "networkidle" })
  assert.equal(await input.inputValue(), "钱包")
  assert.equal(await page.getByRole("button", { name: /^文章 \(/ }).getAttribute("aria-pressed"), "true")
  await input.fill("zz-no-match-20261025")
  await page.getByText("没有找到相关资料", { exact: true }).waitFor()
  assert.equal(await page.locator('[aria-label="搜索结果类型"]').count(), 0)
  await page.getByRole("button", { name: "重置搜索", exact: true }).click()
  await recommendations.waitFor()

  await page.goto(`${base}/articles/member-account-states`, { waitUntil: "networkidle" })
  assert.notEqual(await page.locator("#article-details").getAttribute("open"), null)
  assert.equal(await page.locator("#article-content").isVisible(), true)
  console.log(`PASS search ${width}px: six curated entries, hidden empty types, URL query/type, detail back scroll, reload, no results/reset; article details expanded`)
}

import assert from "node:assert/strict"

export async function checkInterfaceMotion(page, base, prefix, width) {
  const response = await page.goto(base + "/articles/interface-motion-feedback#interface-motion-demo", { waitUntil: "networkidle" })
  assert.equal(response.status(), 200)
  const section = page.locator("#interface-motion-demo")
  const demo = section.locator("[data-interface-motion]")
  await demo.waitFor()
  await page.locator("#article-details[open]").waitFor()
  await page.emulateMedia({ reducedMotion: "no-preference" })
  const next = demo.getByRole("button", { name: "查看下一步", exact: true })
  const restart = demo.getByRole("button", { name: "从头看", exact: true })
  const play = demo.locator("[data-motion-play]")
  const screen = (name) => demo.locator(`[data-motion-screen="${name}"]`)
  const step = async (value) => page.waitForFunction((n) => document.querySelector("[data-interface-motion]")?.getAttribute("data-step") === String(n), value)
  const running = async (value) => page.waitForFunction((state) => document.querySelector("[data-interface-motion]")?.getAttribute("data-motion-running") === String(state), value)
  const show = async (name) => {
    await screen(name).evaluate((node) => node.scrollIntoView({ block: "center", behavior: "instant" }))
    await page.waitForTimeout(80)
  }
  const clickWithoutScroll = async (button) => button.evaluate((node) => node.click())
  const choose = async (name, target) => {
    await demo.getByRole("tab", { name, exact: true }).click()
    await step(0)
    await show(target)
  }
  const capture = async (name) => screen(name).screenshot({ path: `/tmp/interface-motion-${name}-${width}.png`, style: "body > header { visibility: hidden !important; }" })

  assert.equal(await demo.getByRole("tab").count(), 3)
  assert.equal(await demo.getAttribute("data-scene"), "submit")
  await show("submit")
  const submit = demo.locator("[data-motion-submit]")
  // Two clicks in the same browser task exercise the synchronous duplicate guard.
  await submit.evaluate((button) => { button.click(); button.click() })
  await step(1); await running(true)
  assert.equal(await submit.isDisabled(), true)
  assert((await screen("submit").innerText()).includes("本轮演示提交 1 次"))
  await page.waitForTimeout(300)
  await clickWithoutScroll(play)
  await running(false)
  const animation = await submit.locator("svg").evaluate((node) => node.getAnimations().map((item) => ({ time: Number(item.currentTime), state: item.playState })))
  assert(animation.length > 0, "Waiting feedback has an actual CSS animation")
  assert(animation.every((item) => item.state === "paused"), "Pause freezes CSS animation")
  await page.waitForTimeout(2200)
  assert.equal(await demo.getAttribute("data-step"), "1", "Pause freezes the remaining step timer")
  const later = await submit.locator("svg").evaluate((node) => node.getAnimations().map((item) => Number(item.currentTime)))
  later.forEach((time, index) => assert(Math.abs(time - animation[index].time) < 25, "Paused animation does not advance"))
  await clickWithoutScroll(play); await running(true); await step(2)
  assert.equal(await demo.getAttribute("data-motion-running"), "false", "Playback stops at its final step")
  assert.equal(await demo.locator("[data-motion-result]").getAttribute("data-motion-result"), "success")
  assert((await screen("submit").innerText()).includes("待审核"))
  await capture("submit")

  await clickWithoutScroll(restart); await step(0)
  await demo.getByLabel("响应示例", { exact: true }).selectOption("failure")
  const originalTitle = await demo.getByLabel("演示公告标题", { exact: true }).inputValue()
  const originalSummary = await demo.getByLabel("演示公告摘要", { exact: true }).inputValue()
  await clickWithoutScroll(submit); await step(1)
  await clickWithoutScroll(next); await step(2)
  assert.equal(await demo.locator("[data-motion-result]").getAttribute("data-motion-result"), "failure")
  await demo.getByRole("button", { name: "保留内容，回到填写", exact: true }).click()
  await step(0)
  assert.equal(await demo.getByLabel("演示公告标题", { exact: true }).inputValue(), originalTitle)
  assert.equal(await demo.getByLabel("演示公告摘要", { exact: true }).inputValue(), originalSummary)

  await choose("2. 筛选更新", "filter")
  assert.equal(await screen("filter").locator("[data-motion-record]").count(), 3)
  assert.equal(await demo.locator("[data-motion-applied]").innerText(), "全部状态")
  await clickWithoutScroll(demo.getByRole("button", { name: "应用条件", exact: true })); await step(1)
  assert.equal(await screen("filter").locator("[data-motion-record]").count(), 3, "Old records remain during loading")
  assert.equal(await demo.locator("[data-motion-applied]").innerText(), "全部状态")
  await clickWithoutScroll(next); await step(2)
  assert.equal(await demo.locator("[data-motion-applied]").innerText(), "待审核")
  assert.equal(await screen("filter").locator("[data-motion-record]").count(), 2)
  await capture("filter")
  await clickWithoutScroll(restart); await step(0)
  await demo.getByLabel("公告状态", { exact: true }).selectOption("已发布")
  await clickWithoutScroll(demo.getByRole("button", { name: "应用条件", exact: true })); await step(1)
  await clickWithoutScroll(next); await step(2)
  assert.equal(await demo.locator("[data-motion-applied]").innerText(), "已发布")
  assert.equal(await screen("filter").locator("[data-motion-record]").count(), 1)
  assert.equal(await screen("filter").locator("[data-motion-record]").getAttribute("data-motion-record"), "ANN-DEMO-102")

  await choose("3. 弹层与返回", "dialog")
  const opener = screen("dialog").locator('[data-motion-record="ANN-DEMO-101"]').getByRole("button", { name: "详情", exact: true })
  await opener.click(); await step(1)
  const dialog = screen("dialog").getByRole("dialog", { name: "公告详情示意", exact: true })
  await dialog.waitFor()
  assert((await dialog.innerText()).includes("ANN-DEMO-101"))
  assert((await dialog.innerText()).includes("服务时间说明"))
  await page.keyboard.press("Escape"); await step(3)
  await dialog.waitFor({ state: "hidden" })
  assert(await opener.evaluate((node) => document.activeElement === node), "Escape restores original trigger focus")
  assert.equal(await screen("dialog").locator('[data-motion-record="ANN-DEMO-101"]').getAttribute("data-selected"), "true")
  assert((await screen("dialog").innerText()).includes("全部状态"))
  await opener.click(); await step(1)
  await clickWithoutScroll(next); await step(2)
  await capture("dialog")
  await dialog.getByRole("button", { name: "关闭，返回原记录", exact: true }).click(); await step(3)
  assert(await opener.evaluate((node) => document.activeElement === node))

  // Manual opening renders a full, readable static drawer instead of a frozen offscreen first frame.
  await clickWithoutScroll(restart); await step(0)
  await clickWithoutScroll(next); await step(1)
  const manualBox = await screen("dialog").getByRole("dialog").boundingBox()
  const stageBox = await screen("dialog").boundingBox()
  assert(manualBox && stageBox && manualBox.x >= stageBox.x && manualBox.x + manualBox.width <= stageBox.x + stageBox.width + 1)
  await page.keyboard.press("Escape"); await step(3)

  // Leaving the visible stage pauses the same in-flight request rather than completing it invisibly.
  await choose("1. 提交反馈", "submit")
  await demo.getByLabel("响应示例", { exact: true }).selectOption("success")
  await clickWithoutScroll(submit); await step(1); await running(true)
  await page.waitForTimeout(200)
  await page.evaluate(() => scrollTo({ top: document.documentElement.scrollHeight, behavior: "instant" }))
  await running(false)
  await page.waitForTimeout(2200)
  assert.equal(await demo.getAttribute("data-step"), "1", "Offscreen stage remains paused")
  await show("submit"); await running(true); await step(2)

  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.waitForFunction(() => document.querySelector("[data-interface-motion]")?.getAttribute("data-reduced-motion") === "true")
  assert.equal(await play.isDisabled(), true)
  for (const [tab, name, finalStep] of [["1. 提交反馈", "submit", 2], ["2. 筛选更新", "filter", 2], ["3. 弹层与返回", "dialog", 3]]) {
    await choose(tab, name)
    for (let index = 1; index <= finalStep; index++) {
      await clickWithoutScroll(next); await step(index)
      assert.equal(await demo.getAttribute("data-motion-running"), "false")
      const animated = await demo.evaluate((node) => [node, ...node.querySelectorAll("*")].filter((item) => getComputedStyle(item).animationName !== "none").length)
      assert.equal(animated, 0, "Reduced motion uses static readable states")
    }
  }
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await choose("1. 提交反馈", "submit")
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${width}px motion page has no horizontal overflow`)
  for (const link of await section.getByRole("link").all()) {
    const href = await link.getAttribute("href")
    if (href?.startsWith("/")) assert(href.startsWith(prefix + "/articles/"), "Related links retain the deployment prefix")
  }
  await demo.screenshot({ path: `/tmp/interface-motion-checked-${width}.png`, style: "body > header { visibility: hidden !important; }" })
  console.log(`PASS interface motion ${width}px: three scenes, duplicate guard, frozen timer/CSS and resume, failure input, applied filters/records, drawer Escape/focus, offscreen pause, reduced motion, details open and no overflow`)
}
